// Writes docs/BALANCE.md and js/engine/measured.js from a simulator run.
//
//   node tools/sim.mjs 12 --json docs/sim-results.json
//   node tools/calibrate.mjs docs/sim-results.json   (optional, then re-run sim)
//   node tools/balance-report.mjs docs/sim-results.json
import { readFileSync, writeFileSync } from 'node:fs';
import { CARD_LIST, COMPACT_LIST, CARDS, CLANS, CLAN_IDS, RARITY, TIER } from '../js/engine/cards.js';
import { rubric, BANDS, HORIZON } from '../js/engine/rubric.js';
import { checkpointsFor } from '../js/engine/mapgen.js';

const sim = JSON.parse(readFileSync(process.argv[2] || 'docs/sim-results.json'));
const obs = Object.fromEntries(sim.rows.map((r) => [r.id, r]));
const avg = (a) => (a.length ? a.reduce((s, v) => s + v, 0) / a.length : 0);
const f1 = (v) => (Math.round(v * 10) / 10).toFixed(1);
const trig = (c) => (c.trig === 'every' ? `Every ${c.every}` : { build: 'On Build', turn: 'Every turn', sunlit: 'Sunlit', sunlit2: '2 Sunlit', shadow: 'Shadow', event: 'Reactive', passive: 'Passive' }[c.trig]);

const L = [];
L.push('# Astral Expanse — Building Balance');
L.push('');
L.push(`Generated by \`tools/balance-report.mjs\` from ${sim.games} simulated colonies (every one of the 84 three-clan trios, five resource profiles). Re-run it after changing any card.`);
L.push('');
L.push('## 1. Goals');
L.push('');
L.push('- **Rarity means power.** Every building has a rarity – Common, Uncommon or Rare – and rarer buildings are stronger on the rubric. Each clan has **8 Common, 6 Uncommon and 3 Rare** buildings, including two synergy cards (marked `ally`) that feed on a specific other clan\'s resources. The synergy map is one-way: no two clans feed on each other.');
L.push('- **Rarity also means scarcity.** Draw weight is Common ×1.0, Uncommon ×0.6, Rare ×0.3, so a stronger card shows up less often and every clan\'s expected power per draw stays comparable.');
L.push('- **Clans are even.** Any trio containing a given clan should score within ±5% of the average.');
L.push('- **The rubric predicts play.** A card\'s rubric score and its measured score in simulation must both fall inside its rarity band.');
L.push('');
L.push('## 2. The Power Point (PP) rubric');
L.push('');
L.push('Every building is priced in **Power Points**: the Influence it is expected to produce while on the board, plus the value of what it enables for other buildings, minus its drawbacks.');
L.push('');
L.push('```');
L.push('PP = OnBuild');
L.push('   + activations × (points × reliability + utility)        periodic effects');
L.push('   + reactivePoints × triggersPerTurn × horizon             reactive listeners');
L.push('   + (auraPoints + auraUtility) × rate × horizon            passives and auras');
L.push('   + ceil(horizon / 5) × (abilityPoints + abilityUtility)   once-per-era abilities');
L.push('   − drawbacks');
L.push('```');
L.push('');
L.push('| Input | Meaning |');
L.push('|---|---|');
L.push(`| Horizon | Expected turns on the board once drawn: Early ${HORIZON.E}, Mid ${HORIZON.M}, Advanced ${HORIZON.A}. Later tiers unlock later (Mid on turn 6, Advanced on turn 11), so they must hit harder per activation. |`);
L.push('| Activations | From the trigger: Every turn = horizon; Every N turns = horizon ÷ N; Sunlit or Shadow = horizon ÷ 2; Every 2 Sunlit turns = horizon ÷ 4. |');
L.push('| Reliability | Share of activations that find a valid target (an adjacent Ore, a Water in range, and so on). Calibrated from simulation (section 4). |');
L.push('| Utility (Influence-equivalent) | Create a loose token 2 · enabling transform 1 · reveal a deposit 1.5 · open a Cavern 2 · stabilize/shield a hex 1 · repeat another building ≈5 · extra card draw 3 · one Integrity 3. |');
L.push('| Drawbacks | −1 Integrity ≈ 3 PP; self-inflicted Radiation ≈ 1 PP; destroying your own building ≈ its value. |');
L.push('');
L.push('### Rarity bands');
L.push('');
L.push('| Rarity | PP band | Target | Draw weight | Per clan |');
L.push('|---|---|---|---|---|');
for (const [k, b] of Object.entries(BANDS)) L.push(`| ${RARITY[k].n} | ${b.min}–${b.max} | ${b.target} | ×${RARITY[k].w} | ${k === 'C' ? 7 : k === 'U' ? 5 : 3} |`);
L.push('');
L.push('## 3. Results');
L.push('');
const games = sim.games;
L.push(`- Bot win rate on an ordinary sector-1 colony with a three-clan treaty: **${Math.round((100 * sim.wins) / games)}%**; final Influence median **${sim.finals.slice().sort((a, b) => a - b)[Math.floor(games / 2)]}**.`);
L.push(`- Checkpoint curve: need(t) = 1.24 × difficulty × (0.0125t³ + 0.71t² + 4.5t), scaled so a solo clan clears an ordinary sector-1 colony ~90% of the time; each checkpoint asks for the increment since the previous one (×0.9 after the first) → ${checkpointsFor(21, 1).map((c) => `T${c.turn}: ${c.need}`).join(', ')} on a sector-1 21-turn map. Each later sector raises difficulty by 8%, Fault Worlds by +12%, the finale by +15% (+20% per missing Gate Shard).`);
L.push('');
L.push('### Clan balance');
L.push('');
L.push('Average final Influence of every simulated colony whose trio included the clan.');
L.push('');
L.push('| Clan | Avg final Influence | vs. mean | Rubric total PP | Expected PP per draw |');
L.push('|---|---|---|---|---|');
const mean = avg(Object.values(sim.clan));
for (const cl of CLAN_IDS.slice().sort((a, b) => sim.clan[b] - sim.clan[a])) {
  const cs = CARD_LIST.filter((c) => c.cl === cl);
  const tot = cs.reduce((s, c) => s + rubric(c).pp, 0);
  const w = cs.reduce((s, c) => s + RARITY[c.r].w, 0);
  const per = cs.reduce((s, c) => s + RARITY[c.r].w * rubric(c).pp, 0) / w;
  const d = (sim.clan[cl] / mean - 1) * 100;
  L.push(`| ${CLANS[cl].ic} ${CLANS[cl].n} | ${Math.round(sim.clan[cl])} | ${d >= 0 ? '+' : ''}${d.toFixed(1)}% | ${tot.toFixed(0)} | ${per.toFixed(1)} |`);
}
L.push('');
L.push('### Rarity tiers');
L.push('');
L.push('| Rarity | Rubric PP (mean) | Measured PP (mean) | Band |');
L.push('|---|---|---|---|');
for (const k of ['C', 'U', 'R']) {
  const cs = CARD_LIST.filter((c) => c.r === k);
  L.push(`| ${RARITY[k].n} | ${f1(avg(cs.map((c) => rubric(c).pp)))} | ${f1(avg(cs.map((c) => obs[c.id].obs)))} | ${BANDS[k].min}–${BANDS[k].max} |`);
}
const outR = CARD_LIST.filter((c) => !rubric(c).ok).length;
const outM = CARD_LIST.filter((c) => { const b = BANDS[c.r]; const m = obs[c.id].obs; return m < b.min * 0.9 || m > b.max * 1.1; }).length;
L.push('');
L.push(`Cards outside their band on the rubric: **${outR}**. Cards whose measured PP is more than 10% outside their band: **${outM}**.`);
L.push('');
L.push('## 4. Method');
L.push('');
L.push('1. **Design.** Each card gets rubric inputs (points, trigger, estimated reliability, utility) and a rarity.');
L.push('2. **Simulate.** `tools/sim.mjs` plays every trio with a greedy bot. For each candidate placement the bot simulates the full turn plus two quiet turns and keeps the best Influence gain, so it values periodic buildings, not just immediate payoffs. It records each building\'s Influence and activations.');
L.push('3. **Measure.** Measured PP = On-Build points + (later Influence ÷ turns on board) × horizon. This puts measured power on the same scale as the rubric.');
L.push('4. **Calibrate.** `tools/calibrate.mjs` adjusts only the reliability-type inputs (reliability, trigger rates) toward what was measured, damped to 60% per pass to absorb noise. Points, utilities and costs stay as designed, so the rubric remains a pricing tool rather than a copy of the data.');
L.push('5. **Adjust cards.** Any card still outside its band gets a real change: points, range, timer or a fallback effect. Then repeat from step 2.');
L.push('');
L.push('### Structural changes the data forced');
L.push('');
L.push('- **Deposits hold several units** (Ore 3, Ice 3, Wreckage 3, Bio-Loam 3, Gold 2, Organic Seam 2, …). A conversion puts its product on an adjacent free hex and depletes the deposit by one. Before this change converter clans (Ironwake, Verdant, Wreckborn) ran out of inputs after one activation and scored about 20% below average.');
L.push('- **Converters reach range 2** (Smelting Stack, Algae Tank, Breaker Yard, …), so two-building chains can actually be built.');
L.push('- **Starters are self-sufficient.** Every clan opens with a guaranteed producer, and the map always seeds that clan\'s key resources near the landing zone. Spore Seeder plants its own Organic Seam when it has nothing to convert.');
L.push('- **Board-counting scorers were cut hard.** Data Scriptorium, Network Brain, Skyhook, Path Optimizer and Pressure Dome scored 2–4× their band because large networks are easy to build.');
L.push('- **Rarely-firing payoffs got fallbacks.** Many reactive cards also have a small periodic effect, so a card never sits completely idle.');
L.push('- **Fresh hands.** Each turn deals 3 fresh cards; unbuilt ones are salvaged for +1 each (opening-hand and returned cards are kept). The old 5-card hand clogged with Early cards and scrapped new draws unseen, so Advanced cards now reach the board 2–3× as often and the bot only builds situational cards in good spots. That selection lifts measured PP about 12% over the rubric across the board, so bands are judged on clear relative outliers. The checkpoint curve gained a cubic term for the steeper late game, and Masterwork dropped from 1.25× to 1.2× the checkpoint total.');
L.push('');
L.push('### Limits');
L.push('');
L.push('- The bot is greedy with a 3-turn horizon. It undervalues long setups and abilities (it uses one only when the immediate gain is ≥10), so combo-heavy Rares may play stronger in human hands.');
L.push('- This report plays three-clan treaties only. Solo and two-clan treaties, boss maps and techs are covered by `tools/simsuite.mjs` (solo, duos, treaty, boss, tech suites); a lone clan is tuned to win about 90% of sector-1 colonies. The overworld economy is not simulated; `tools/expedition-smoke.mjs` only checks that whole expeditions run end to end.');
L.push('');
L.push('## 5. Card tables');
L.push('');
L.push('PP = rubric Power Points · Meas. = measured PP · Act/turn = observed activations per turn on board.');
for (const cl of CLAN_IDS) {
  L.push('');
  L.push(`### ${CLANS[cl].ic} ${CLANS[cl].n} — ${CLANS[cl].s}`);
  L.push('');
  L.push(CLANS[cl].d);
  L.push('');
  L.push('| Tier | Rarity | Building | Tags | Trigger | PP | Meas. | Act/turn | Effect |');
  L.push('|---|---|---|---|---|---|---|---|---|');
  for (const t of ['E', 'M', 'A']) {
    for (const c of CARD_LIST.filter((x) => x.cl === cl && x.t === t)) {
      const o = obs[c.id];
      L.push(`| ${TIER[t]} | ${RARITY[c.r].n} | **${c.n}** | ${c.tags.join(' · ')} | ${trig(c)} | ${f1(rubric(c).pp)} | ${f1(o.obs)} | ${o.apt.toFixed(2)} | ${c.text.replace(/\|/g, '/')} |`);
    }
  }
}
L.push('');
L.push('## 6. Clan Compacts');
L.push('');
L.push('Each pair of clans in a treaty upgrades one building per clan into a compact that feeds on the partner; it replaces the base card in that clan\'s pool. Compacts price at 1.3× their rarity band. Meas. counts only games where the treaty unlocked it, so it is inflated by selection: a compact is built where its partner already is.');
L.push('');
L.push('| Clan | Partner | Compact | Upgrades | Rarity | PP | Meas. | Base meas. | Placed | Compact effect |');
L.push('|---|---|---|---|---|---|---|---|---|---|');
for (const c of COMPACT_LIST) {
  const o = obs[c.id] || { obs: 0, placed: 0 };
  L.push(`| ${CLANS[c.cl].ic} | ${CLANS[c.partner].ic} | **${c.n}** | ${CARDS[c.base].n} | ${RARITY[c.r].n} | ${f1(rubric(c).pp)} | ${f1(o.obs)} | ${f1((obs[c.base] || { obs: 0 }).obs)} | ${o.placed} | ${c.text.slice(c.text.indexOf('Compact:') + 9).replace(/\|/g, '/')} |`);
}
L.push('');
L.push('## 7. Re-running');
L.push('');
L.push('```sh');
L.push('node tools/rubric-check.mjs                          # rubric PP and band check');
L.push('node tools/sim.mjs 12 --json docs/sim-results.json   # ~2 min on 10 cores');
L.push('node tools/calibrate.mjs docs/sim-results.json       # optional: update reliability inputs');
L.push('node tools/balance-report.mjs docs/sim-results.json  # regenerate this file');
L.push('```');
writeFileSync('docs/BALANCE.md', L.join('\n') + '\n');

const measured = Object.fromEntries(sim.rows.map((r) => [r.id, Math.round(r.obs * 10) / 10]));
writeFileSync('js/engine/measured.js', `// Measured Power Points per card from tools/sim.mjs (${sim.games} colonies).\n// Regenerated by tools/balance-report.mjs – do not edit by hand.\nexport const MEASURED = ${JSON.stringify(measured)};\n`);
console.log(`wrote docs/BALANCE.md (${outR} rubric / ${outM} measured outliers) and js/engine/measured.js`);
